/** Split a stored CSV string into trimmed values. */
export function splitDestinationList(value?: string | null): string[] {
  if (!value?.trim()) return [];
  return value
    .split(",")
    .map((part) => part.trim())
    .filter(Boolean);
}

/** Join selected values for storage (comma-separated string). */
export function joinDestinationList(values: string[]): string {
  return values.filter(Boolean).join(", ");
}

/** City/region options for the currently selected countries. */
export function getCityOptionsForCountries(countries: string[]): {
  value: string;
  label: string;
}[] {
  const options: { value: string; label: string }[] = [];
  const seen = new Set<string>();

  for (const country of countries) {
    const cities = CITIES_BY_COUNTRY[country] ?? [];
    for (const city of cities) {
      if (seen.has(city)) continue;
      seen.add(city);
      options.push({
        value: city,
        label: countries.length > 1 ? `${city} (${country})` : city,
      });
    }
  }

  return options;
}
